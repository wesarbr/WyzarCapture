use crate::{core::AppResult, persistence};
use std::{
    collections::BTreeMap,
    path::{Path, PathBuf},
};
pub struct Journal {
    path: PathBuf,
    values: BTreeMap<String, String>,
    pub bundle: PathBuf,
}
impl Journal {
    pub fn begin(data_dir: &Path, output: &Path) -> AppResult<Self> {
        let id = format!("{}-{}", crate::settings::unique_stamp(), std::process::id());
        let path = data_dir.join("Recovery").join(format!("{id}.recording"));
        if output.exists() {
            return Err(crate::i18n::tr("O arquivo de saída já existe").into());
        }
        let bundle = output
            .parent()
            .ok_or(crate::i18n::tr("Destino sem pasta"))?
            .join(format!(".wyzar-{id}"));
        std::fs::create_dir(&bundle).map_err(|e| e.to_string())?;
        let values = BTreeMap::from([
            ("version".into(), "2".into()),
            ("output".into(), output.to_string_lossy().into()),
            ("bundle".into(), bundle.to_string_lossy().into()),
            ("id".into(), id),
            ("segments".into(), "0".into()),
            ("frames".into(), "0".into()),
        ]);
        persistence::write(&bundle.join("session.wyz"), &values)?;
        persistence::write(&path, &values)?;
        Ok(Self {
            path,
            values,
            bundle,
        })
    }
    pub fn segment_path(&self, index: u32) -> PathBuf {
        self.bundle.join(format!("segment-{index:06}.mp4"))
    }
    pub fn commit_segment(&mut self, count: u32, frames: u64) -> AppResult<()> {
        self.values.insert("segments".into(), count.to_string());
        self.values.insert("frames".into(), frames.to_string());
        persistence::write(&self.bundle.join("session.wyz"), &self.values)?;
        persistence::write(&self.path, &self.values)
    }
    pub fn segments(&self) -> Vec<PathBuf> {
        let count = self
            .values
            .get("segments")
            .and_then(|s| s.parse::<u32>().ok())
            .unwrap_or(0);
        (0..count).map(|i| self.segment_path(i)).collect()
    }
    pub fn committed_count(&self) -> u32 {
        self.values
            .get("segments")
            .and_then(|n| n.parse().ok())
            .unwrap_or(0)
    }
    pub fn checkpoint(&mut self, frames: u64) -> AppResult<()> {
        self.values.insert("frames".into(), frames.to_string());
        persistence::write(&self.path, &self.values)
    }
    pub fn complete(self) -> AppResult<()> {
        cleanup_bundle(&self.bundle)?;
        std::fs::remove_file(self.path).map_err(|e| e.to_string())
    }
}
#[derive(Clone, Debug)]
pub struct Candidate {
    pub journal: PathBuf,
    pub output: PathBuf,
    pub bundle: Option<PathBuf>,
    pub segments: Vec<PathBuf>,
    pub detail: String,
}
pub fn discard_paths(candidate: &Candidate) -> Vec<PathBuf> {
    let mut paths = vec![];
    if let Some(bundle) = &candidate.bundle {
        paths.push(bundle.clone());
        // Keep companions of an already saved final video; only unfinished-session audio is owned here.
        if !candidate.output.exists() {
            for ext in ["mic.wav", "system.wav", "audio.wav"] {
                let path = candidate.output.with_extension(ext);
                if path.is_file() {
                    paths.push(path);
                }
            }
        }
    }
    paths.push(candidate.journal.clone());
    paths
}
fn safe_directory(path: &Path) -> bool {
    use std::os::windows::fs::MetadataExt;
    path.is_absolute()
        && path
            .ancestors()
            .all(|p| std::fs::symlink_metadata(p).is_ok_and(|m| m.file_attributes() & 0x400 == 0))
}
fn cleanup_bundle(bundle: &Path) -> AppResult<()> {
    if !safe_directory(bundle)
        || !bundle
            .file_name()
            .is_some_and(|n| n.to_string_lossy().starts_with(".wyzar-"))
    {
        return Err(crate::i18n::tr("Pasta de recuperação fora do limite seguro").into());
    }
    // Delete only files generated by this subsystem, never recurse through imported paths.
    for entry in std::fs::read_dir(bundle).map_err(|e| e.to_string())? {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.is_file()
            && (path.file_name().is_some_and(|n| n == "session.wyz")
                || path
                    .file_name()
                    .is_some_and(|n| n.to_string_lossy().starts_with("segment-"))
                    && path.extension().is_some_and(|n| n == "mp4"))
        {
            std::fs::remove_file(path).map_err(|e| e.to_string())?;
        }
    }
    std::fs::remove_dir(bundle).map_err(|e| e.to_string())
}
pub fn candidates(data_dir: &Path) -> Vec<Candidate> {
    pending(data_dir)
        .into_iter()
        .filter_map(|journal| {
            let values = persistence::read(&journal).ok()?;
            let output: PathBuf = values.get("output")?.into();
            if !output.is_absolute() {
                return None;
            }
            if values.get("version").is_some_and(|v| v == "1") {
                return Some(Candidate {
                    journal,
                    output,
                    bundle: None,
                    segments: vec![],
                    detail: crate::i18n::tr("Sessão antiga: apenas MP4 já finalizado pode ser reimportado.").into(),
                });
            }
            if values.get("version")? != "2" {
                return None;
            }
            let bundle: PathBuf = values.get("bundle")?.into();
            let id = values.get("id")?;
            if bundle.file_name()?.to_str()? != format!(".wyzar-{id}")
                || bundle.parent() != output.parent()
                || !safe_directory(&bundle)
            {
                return None;
            }
            let committed = persistence::read(&bundle.join("session.wyz")).ok()?;
            if committed.get("id") != Some(id) {
                return None;
            }
            let count = committed.get("segments")?.parse::<u32>().ok()?.min(100_000);
            let segments = (0..count)
                .map(|i| bundle.join(format!("segment-{i:06}.mp4")))
                .filter(|p| p.is_file())
                .collect::<Vec<_>>();
            let detail = { let __wyzar_i18n_0 = &(segments.len()); crate::i18n::format_text(crate::i18n::tr("{} segmento(s) finalizado(s). O último segmento em aberto pode ter sido perdido."), &[("0", format!("{}", __wyzar_i18n_0))]) };
            Some(Candidate {
                journal,
                output,
                bundle: Some(bundle),
                segments,
                detail,
            })
        })
        .collect()
}
pub fn recover(candidate: &Candidate, output: &Path) -> AppResult<PathBuf> {
    let _runtime = crate::platform::windows::Runtime::new(true)?;
    if candidate.output.is_file()
        && crate::platform::windows::media::Reader::open(&candidate.output)
            .and_then(|mut r| r.frame_at((r.meta.duration - 0.1).max(0.)))
            .is_ok_and(|f| f.is_some())
    {
        return Ok(candidate.output.clone());
    }
    if candidate.bundle.is_none() {
        let mut reader = crate::platform::windows::media::Reader::open(&candidate.output)?;
        if reader.frame_at(0.)?.is_none() {
            return Err(crate::i18n::tr("O MP4 antigo não tem quadros recuperáveis").into());
        }
        return Ok(candidate.output.clone());
    }
    let mut valid = vec![];
    for path in &candidate.segments {
        let mut reader = crate::platform::windows::media::Reader::open(path)?;
        if reader.frame_at(0.)?.is_none() {
            return Err(crate::i18n::tr(
                "Um segmento não pôde ser decodificado; os arquivos foram preservados",
            )
            .into());
        }
        valid.push(path.clone());
    }
    if valid.is_empty() {
        return Err(crate::i18n::tr(
            "Nenhum segmento foi finalizado antes da interrupção. Os arquivos foram preservados.",
        )
        .into());
    }
    crate::platform::windows::media::concatenate(&valid, output)?;
    let mut reader = crate::platform::windows::media::Reader::open(output)?;
    if reader
        .frame_at((reader.meta.duration - 0.1).max(0.))?
        .is_none()
    {
        return Err(crate::i18n::tr(
            "Não foi possível validar o arquivo recuperado; os segmentos foram preservados",
        )
        .into());
    }
    drop(reader);
    let mut owned = vec![output.to_path_buf()];
    for ext in ["mic.wav", "system.wav", "audio.wav"] {
        let source = candidate.output.with_extension(ext);
        if source.is_file() {
            let destination = output.with_extension(ext);
            if let Err(error) = crate::audio::wav::recover_copy(&source, &destination) {
                for path in owned {
                    let _ = std::fs::remove_file(path);
                }
                return Err(crate::i18n::format_text(
                    crate::i18n::tr(
                        "O áudio auxiliar não pôde ser recuperado. Os originais foram preservados: {error}",
                    ),
                    &[("error", format!("{}", error))],
                ));
            }
            owned.push(destination);
        }
    }
    Ok(output.into())
}
pub fn acknowledge(candidate: &Candidate, recovered: &Path) -> AppResult<()> {
    if candidate.bundle.is_some() && recovered != candidate.output {
        for ext in ["mic.wav", "system.wav", "audio.wav"] {
            let source = candidate.output.with_extension(ext);
            let destination = recovered.with_extension(ext);
            if source.is_file() {
                if !destination.is_file() || crate::audio::waveform(&destination, 1).is_err() {
                    return Err(crate::i18n::tr(
                        "O auxiliar original foi preservado: cópia recuperada não confirmada.",
                    )
                    .into());
                }
                std::fs::remove_file(source).map_err(|e| e.to_string())?;
            }
        }
    }
    if let Some(bundle) = &candidate.bundle {
        cleanup_bundle(bundle)?;
    }
    std::fs::remove_file(&candidate.journal).map_err(|e| e.to_string())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn checkpoints_preserve_only_committed_segments_and_legacy_sessions() {
        let root = std::env::current_dir()
            .unwrap()
            .join("validation/unit")
            .join(format!("recovery-{}", crate::settings::unique_stamp()));
        std::fs::create_dir_all(&root).unwrap();
        let mut journal = Journal::begin(&root, &root.join("Original.mp4")).unwrap();
        std::fs::write(journal.segment_path(0), b"fixture").unwrap();
        std::fs::write(journal.segment_path(1), b"unfinished").unwrap();
        journal.commit_segment(1, 50).unwrap();
        let found = candidates(&root);
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].segments.len(), 1);
        let companion = found[0].output.with_extension("system.wav");
        std::fs::write(&companion, b"unfinished audio").unwrap();
        assert!(discard_paths(&found[0]).contains(&companion));
        std::fs::write(&found[0].output, b"already saved video").unwrap();
        assert!(!discard_paths(&found[0]).contains(&companion));
        assert!(!discard_paths(&found[0]).contains(&found[0].output));
        let mut malicious = persistence::read(&found[0].journal).unwrap();
        malicious.insert("bundle".into(), root.to_string_lossy().into());
        persistence::write(&found[0].journal, &malicious).unwrap();
        assert!(candidates(&root).is_empty());
        journal.complete().unwrap();
        std::fs::remove_dir_all(root).unwrap();
    }
}
pub fn pending(data_dir: &Path) -> Vec<PathBuf> {
    std::fs::read_dir(data_dir.join("Recovery"))
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|s| s == "recording"))
        .collect()
}
